package com.gitfix.github;

import lombok.RequiredArgsConstructor;
import org.kohsuke.github.*;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import java.io.IOException;

@Service
@RequiredArgsConstructor
public class PullRequestService {

    private static final Logger log = LoggerFactory.getLogger(PullRequestService.class);
    private static final String PR_LABEL = "gitfix-ai";

    /**
     * Opens a Pull Request using Kohsuke GitHub API with clean formatting, closes clause, and label.
     */
    public String createPullRequest(String token, PullRequestDetails details) {
        log.info("Opening Pull Request for {} on branch {}", details.getRepoFullName(), details.getBranchName());

        try {
            GitHub gitHub = new GitHubBuilder().withOAuthToken(token).build();
            GHRepository repository = gitHub.getRepository(details.getRepoFullName());

            String baseBranch = details.getBaseBranch();
            if (baseBranch == null || baseBranch.isBlank()) {
                baseBranch = repository.getDefaultBranch();
            }

            String title = "Fix: " + details.getIssueTitle() + " (Fixes #" + details.getIssueNumber() + ")";
            String body = buildPrBody(details);

            GHPullRequest pr = repository.createPullRequest(
                    title,
                    details.getBranchName(),
                    baseBranch,
                    body
            );

            log.info("Created PR #{} at {}", pr.getNumber(), pr.getHtmlUrl());

            // Add label
            try {
                pr.addLabels(PR_LABEL);
            } catch (Exception e) {
                log.warn("Could not attach '{}' label to PR #{}: {}", PR_LABEL, pr.getNumber(), e.getMessage());
            }

            // Post comment on the issue
            try {
                GHIssue issue = repository.getIssue(details.getIssueNumber());
                issue.comment("🤖 **GitFix AI** has generated a tested pull request for this issue: " + pr.getHtmlUrl().toString());
            } catch (Exception e) {
                log.warn("Could not post comment on issue #{}: {}", details.getIssueNumber(), e.getMessage());
            }

            return pr.getHtmlUrl().toString();

        } catch (IOException e) {
            log.error("Failed to create GitHub Pull Request: {}", e.getMessage(), e);
            throw new IllegalStateException("Failed to create Pull Request: " + e.getMessage(), e);
        }
    }

    private String buildPrBody(PullRequestDetails details) {
        StringBuilder sb = new StringBuilder();
        sb.append("## 🤖 GitFix AI Automated Pull Request\n\n");

        sb.append("### 📝 Summary\n");
        sb.append(details.getExplanation() != null ? details.getExplanation() : "Automated bugfix generated by GitFix AI.").append("\n\n");

        sb.append("### 📂 Files Changed\n");
        if (details.getFilesChanged() != null && !details.getFilesChanged().isEmpty()) {
            for (String file : details.getFilesChanged()) {
                sb.append("- `").append(file).append("`\n");
            }
        } else {
            sb.append("- *(See PR file diff)*\n");
        }
        sb.append("\n");

        if (details.getRetrievedFiles() != null && !details.getRetrievedFiles().isEmpty()) {
            sb.append("### 🔍 Retrieved Code Context\n");
            for (String file : details.getRetrievedFiles()) {
                sb.append("- `").append(file).append("`\n");
            }
            sb.append("\n");
        }

        sb.append("### 🧪 Sandbox Test Results\n");
        sb.append("✅ All automated tests compiled and passed cleanly inside an isolated Docker sandbox container.\n\n");

        sb.append("---\n");
        sb.append("Closes #").append(details.getIssueNumber()).append("\n");
        return sb.toString();
    }
}
